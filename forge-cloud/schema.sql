CREATE TABLE IF NOT EXISTS tasks (
 id TEXT PRIMARY KEY, title TEXT NOT NULL, prompt TEXT NOT NULL, repo TEXT NOT NULL,
 branch TEXT NOT NULL, mode TEXT NOT NULL, model TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'queued',
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL, state TEXT NOT NULL DEFAULT '{}',
 result TEXT, pr_url TEXT, error TEXT, lease_until INTEGER NOT NULL DEFAULT 0, steps INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS tasks_status_created ON tasks(status,created_at);
CREATE TABLE IF NOT EXISTS events (
 id INTEGER PRIMARY KEY AUTOINCREMENT, task_id TEXT NOT NULL, kind TEXT NOT NULL, message TEXT NOT NULL, created_at TEXT NOT NULL,
 FOREIGN KEY(task_id) REFERENCES tasks(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS events_task_id ON events(task_id,id);

CREATE TABLE IF NOT EXISTS usage (key TEXT PRIMARY KEY,count INTEGER NOT NULL DEFAULT 0);
